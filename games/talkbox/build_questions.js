// Build questions.js from parts/*.txt (pipe-delimited). Run: node build_questions.js
const fs = require('fs');
const TYPES = new Set(['daily','fun','feel','memory','dream','value','curious']);
const SCENES = new Set(['f','p','fp']);
const files = { 1:['L1a','L1b','L1c'], 2:['L2a','L2b','L2c'], 3:['L3a','L3b','L3c'] };
const hash = s => { let h = 5381; for (const ch of s) h = ((h*33) ^ ch.codePointAt(0)) >>> 0; return h.toString(36); };
const errors = [];
const cards = [], seenZh = new Map(), seenId = new Map();
for (const [lv, list] of Object.entries(files)) for (const f of list) {
  fs.readFileSync(`parts/${f}.txt`, 'utf8').split('\n').forEach((line, i) => {
    if (!line.trim()) return;
    const p = line.split('|');
    const where = `${f}:${i+1}`;
    if (p.length !== 4) return errors.push(`${where} fields=${p.length}: ${line}`);
    const [scenes, type, zh, en] = p.map(x => x.trim());
    if (!SCENES.has(scenes)) errors.push(`${where} bad scene ${scenes}`);
    if (!TYPES.has(type)) errors.push(`${where} bad type ${type}`);
    if (!zh || !en) errors.push(`${where} empty text`);
    if (/[\u4e00-\u9fff]/.test(en)) errors.push(`${where} CJK in English: ${en}`);
    if (!/[\u4e00-\u9fff]/.test(zh)) errors.push(`${where} no CJK in zh`);
    if (/[\u3105-\u3129]/.test(zh)) errors.push(`${where} bopomofo in zh`);
    if (seenZh.has(zh)) errors.push(`${where} duplicate zh (also ${seenZh.get(zh)}): ${zh}`);
    seenZh.set(zh, where);
    const id = 'q' + hash(zh);
    if (seenId.has(id)) errors.push(`${where} id collision ${id}`);
    seenId.set(id, where);
    cards.push({ id, level: +lv, scenes, type, zh, en });
  });
}
const chals = fs.readFileSync('parts/challenges.txt', 'utf8').split('\n').filter(l => l.trim()).map((l, i) => {
  const p = l.split('|'); if (p.length !== 2) errors.push(`challenges:${i+1} fields=${p.length}`);
  return { id: 'c' + hash(p[0]), zh: p[0].trim(), en: (p[1]||'').trim() };
});
// report
const count = (arr, f) => arr.reduce((m, c) => (m[f(c)] = (m[f(c)]||0)+1, m), {});
console.log('cards', cards.length, 'challenges', chals.length);
console.log('by level', count(cards, c=>c.level));
console.log('by scene', count(cards, c=>c.scenes));
console.log('by type', count(cards, c=>c.type));
const grid = count(cards, c=>`L${c.level}/${c.type}`); console.log('level/type', grid);
console.log('family-eligible', cards.filter(c=>c.scenes.includes('f')).length, 'friends-eligible', cards.filter(c=>c.scenes.includes('p')).length);
if (errors.length) { console.log('ERRORS\n' + errors.join('\n')); process.exit(1); }
fs.writeFileSync('questions.js', '// Auto-generated by build_questions.js. Edit parts/*.txt, not this file.\nwindow.TB_DATA = ' + JSON.stringify({ cards, challenges: chals }) + ';\n');
console.log('wrote questions.js', fs.statSync('questions.js').size, 'bytes');
